#!/usr/bin/env python3
"""Sound mix for the RubbleFront trailer: narration over the game's own music, with the game's own sound effects
(recorded with the footage, so they stay in sync) under both.

    python3 mixrf.py mix.json out.wav

mix.json:
  { "dur": 82.0, "sr": 48000,
    "narration": [ {"file": ".../scene-1.mp3", "t": 0.4, "gain_db": 0} ],        # already normalised to -16 LUFS
    "sfx":   [ {"file": "clip.wav", "in": 0.5, "dur": 5.0, "t": 0.0, "gain_db": -3} ],   # audio recorded with the clip
    "music": { "file": ".../title.ogg", "in": 0, "t": 0, "gain_db": -24, "fade_in": 1.0, "fade_out": 2.5,
               "duck_db": -7, "pitch": 1.0 },
    "peak_db": -2.0 }

Music is ducked while narration speaks (quick attack, slow release). The sound effects are ducked a little under the voice too.
Output is 48 kHz stereo 16-bit WAV, peak limited. No third-party audio is used: the music and the effects are the game's own,
generated by its audio code (docs/audio.md in the game repository).
"""
import json, subprocess, sys, wave
from pathlib import Path
import numpy as np

SR = 48000


def load(path, ss=0.0, t=None):
    cmd = ["ffmpeg", "-v", "error", "-ss", str(ss)]
    if t is not None:
        cmd += ["-t", str(t)]
    cmd += ["-i", str(path), "-f", "f32le", "-ac", "2", "-ar", str(SR), "-"]
    raw = subprocess.run(cmd, capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype="<f4").reshape(-1, 2).copy()


def db(x):
    return 10 ** (x / 20)


def place(mix, x, t0, gain=1.0):
    i0 = int(round(t0 * SR))
    if i0 < 0:
        x = x[-i0:]
        i0 = 0
    n = min(len(x), len(mix) - i0)
    if n > 0:
        mix[i0 : i0 + n] += x[:n] * gain


def envelope(n, windows, low, att=0.05, rel=0.45):
    env = np.ones(n, dtype=np.float32)
    for a, b in windows:
        env[max(0, int(a * SR)) : min(n, int(b * SR))] = low
    out = np.empty_like(env)
    cur = 1.0
    ka, kr = 1 - np.exp(-1 / (att * SR)), 1 - np.exp(-1 / (rel * SR))
    for i in range(n):
        tgt = env[i]
        cur += (tgt - cur) * (ka if tgt < cur else kr)
        out[i] = cur
    return out


def main():
    spec = json.loads(Path(sys.argv[1]).read_text())
    out = Path(sys.argv[2])
    n = int(spec["dur"] * SR)
    voice = np.zeros((n, 2), np.float32)
    fx = np.zeros((n, 2), np.float32)
    mus = np.zeros((n, 2), np.float32)
    windows = []
    for e in spec.get("narration", []):
        x = load(e["file"])
        place(voice, x, e["t"], db(e.get("gain_db", 0)))
        windows.append((e["t"] - 0.15, e["t"] + len(x) / SR + 0.25))
    for e in spec.get("sfx", []):
        x = load(e["file"], e.get("in", 0.0), e["dur"])
        # short fades so a cut never clicks
        f = int(0.01 * SR)
        if len(x) > 2 * f:
            x[:f] *= np.linspace(0, 1, f)[:, None]
            x[-f:] *= np.linspace(1, 0, f)[:, None]
        place(fx, x, e["t"], db(e.get("gain_db", 0)))
    m = spec.get("music")
    if m:
        x = load(m["file"], m.get("in", 0.0), spec["dur"] - m.get("t", 0.0))
        g = np.ones(len(x), np.float32)
        fi, fo = int(m.get("fade_in", 1.0) * SR), int(m.get("fade_out", 2.0) * SR)
        if fi:
            g[:fi] = np.linspace(0, 1, fi) ** 2
        if fo and fo < len(g):
            g[-fo:] *= np.linspace(1, 0, fo) ** 2
        place(mus, x * g[:, None], m.get("t", 0.0), db(m.get("gain_db", -24)))
    env_m = envelope(n, windows, db(spec.get("music", {}).get("duck_db", -7)))
    env_f = envelope(n, windows, db(spec.get("sfx_duck_db", -3)))
    mix = voice + mus * env_m[:, None] + fx * env_f[:, None]
    pk = float(np.abs(mix).max()) or 1.0
    lim = db(spec.get("peak_db", -2.0))
    if pk > lim:
        mix *= lim / pk
    out.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(out), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((np.clip(mix, -1, 1) * 32767).astype("<i2").tobytes())
    print(f"mix: {spec['dur']:.1f}s, {len(spec.get('narration', []))} lines, {len(spec.get('sfx', []))} sfx, peak {20*np.log10(pk):.1f} dBFS before limit -> {out}")


if __name__ == "__main__":
    main()
