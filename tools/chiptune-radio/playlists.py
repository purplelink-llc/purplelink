#!/usr/bin/env python3.12
"""The playlists of the ambient channel and which video goes in which, worked out from the render metadata. It only plans; it never talks to YouTube.

    python3.12 playlists.py                          # read every <slug>/<slug>.json under $AMBIENT_OUT, print the plan
    python3.12 playlists.py --out plan.json          # also write it, for scripts/yt-playlists.py
    python3.12 playlists.py --items items.json       # plan from a hand-made list instead (a JSON list of {slug, title, theme, sound, season, uhd, dark, hours})

Why playlists: the YouTube TV app and search show a channel's videos in playlists, and a viewer who finishes one video is offered the next in its playlist, which
is how a 10 hour fireplace turns into a second and a third. A playlist is also its own search result, so each title is a phrase people type.

Each rule below says which videos a playlist takes; a video may be in several. A playlist with no videos is left out of the plan, so nothing empty is created.
The plan is the input to `scripts/yt-playlists.py`, which creates or updates the playlists through the same guarded API path as the uploads (and by default
only prints what it would do).
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

DEFAULT_ROOT = "/Volumes/Extreme SSD/PurplelinkVideos/ambient"


def _is_fire(v: dict) -> bool:
    return v["sound"] == "fireplace" or v["view"] == "fireplace"


# key, title, description, rule. Titles are phrases from the keyword research (keywords.py); descriptions say plainly what is inside and claim nothing else.
PLAYLISTS = [
    {"key": "christmas-fireplace-4k", "title": "Christmas Fireplace 4K",
     "description": "Pixel-art Christmas fireplaces in 4K, with a crackling fire and no music. Long videos made to play on a TV all evening.",
     "rule": lambda v: v["season"] == "christmas" and v["uhd"] and _is_fire(v)},
    {"key": "cozy-christmas-ambience", "title": "Cozy Christmas Ambience",
     "description": "Pixel-art Christmas cabins and study rooms with original chiptune and lofi music, or with the sound of a fire. Every sound and picture is generated by code.",
     "rule": lambda v: v["season"] == "christmas" and not _is_fire(v)},
    {"key": "new-years-eve-ambience", "title": "New Year's Eve Ambience",
     "description": "Pixel-art rooms decorated for New Year's Eve, with original music or ambient sound.",
     "rule": lambda v: v["season"] == "newyear"},
    {"key": "black-screen-sleep-sounds", "title": "Black Screen Sleep Sounds",
     "description": "Long steady sounds (brown, pink and white noise, rain, fan, wind and more) over a picture that dims to a black screen after a few minutes and leaves the sound on.",
     "rule": lambda v: v["dark"] > 0},
    {"key": "campfire-ambience", "title": "Campfire Ambience",
     "description": "A pixel-art campfire in a night forest: crackling fire, wind and crickets, with music or without.",
     "rule": lambda v: v["theme"] == "campfire"},
    {"key": "study-room-ambience", "title": "Study Room Ambience",
     "description": "A pixel-art study room that goes through a day and night, with rain, a cat and a visiting dog. Music or ambient sound for reading, studying and working.",
     "rule": lambda v: v["theme"] == "study" and v["season"] != "halloween"},
    {"key": "winter-cabin-ambience", "title": "Winter Cabin Ambience",
     "description": "A pixel-art snowed-in cabin: snow at the window, a fireplace, a lit tree and a cat on the rug.",
     "rule": lambda v: v["theme"] == "winter" and v["season"] != "christmas"},
    {"key": "halloween-ambience", "title": "Halloween Ambience",
     "description": "A pixel-art Halloween porch and a Halloween study room: jack-o'-lanterns, a black cat, fog and bats, with original music or low wind.",
     "rule": lambda v: v["theme"] == "halloween" or v["season"] == "halloween"},
]
KEYS = [p["key"] for p in PLAYLISTS]


def normalise(item: dict) -> dict:
    """One video as the rules see it, from either a longform_pub metadata file ({"slug", "title", "render": {...}}) or a hand-made item."""
    r = item.get("render") or {}
    get = lambda k, d=None: item.get(k, r.get(k, d))
    dark = get("dark", get("dark_after_seconds")) or 0
    return {"slug": item["slug"], "title": item.get("title", ""), "theme": get("theme", ""), "sound": get("sound", "chiptune") or "chiptune",
            "season": get("season") or "", "view": get("view") or "", "uhd": bool(get("uhd", False)), "dark": float(dark),
            "hours": round(float(get("hours", (get("seconds", 0) or 0) / 3600)), 2), "video_id": item.get("video_id", "")}


def plan_from_items(items: list) -> list:
    vids = sorted((normalise(i) for i in items), key=lambda v: v["slug"])
    out = []
    for p in PLAYLISTS:
        members = [v for v in vids if p["rule"](v)]
        if members:
            out.append({"key": p["key"], "title": p["title"], "description": p["description"],
                        "videos": [{k: v[k] for k in ("slug", "title", "video_id") if v[k] or k != "video_id"} for v in members]})
    return out


def items_from_dir(root: Path) -> list:
    """Every <slug>/<slug>.json that longform_pub.py meta wrote under `root`."""
    items = []
    for d in sorted(p for p in Path(root).iterdir() if p.is_dir()):
        f = d / f"{d.name}.json"
        if f.is_file():
            try:
                m = json.loads(f.read_text())
            except ValueError:
                continue
            if isinstance(m, dict) and "title" in m and "render" in m:
                m.setdefault("slug", d.name)
                items.append(m)
    return items


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=os.environ.get("AMBIENT_OUT", DEFAULT_ROOT))
    ap.add_argument("--items", help="a JSON list of videos instead of reading the metadata files")
    ap.add_argument("--out", help="write the plan here as JSON")
    a = ap.parse_args(argv)
    items = json.loads(Path(a.items).read_text()) if a.items else items_from_dir(Path(a.root))
    plan = plan_from_items(items)
    for p in plan:
        print(f"{p['title']}  ({len(p['videos'])})")
        for v in p["videos"]:
            print(f"    {v['slug']}: {v['title']}")
    if not plan:
        print("no videos match any playlist")
    if a.out:
        Path(a.out).write_text(json.dumps({"playlists": plan}, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
