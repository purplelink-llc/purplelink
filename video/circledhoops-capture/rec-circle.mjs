import { open, B, record, drawCircle } from './caplib.mjs';
const out = process.argv[2];
const { browser, page } = await open();
await page.goto(`${B}/leagues/lg-demo/lineup`, { waitUntil: 'load' }); await page.waitForTimeout(3000);
await page.getByText('Next week', { exact: true }).first().click();
await page.waitForTimeout(1500);
const rec = await record(page, `${out}/_frames_circle`);
await page.waitForTimeout(900);
rec.mark('tap-row');
await page.getByRole('button', { name: /Tariq Monroe/ }).first().click();
await page.waitForTimeout(1400);
const games = page.locator('[role=dialog] button').filter({ hasText: /PM/ });
const n = await games.count();
const box = await games.nth(Number(process.env.GAME ?? 1)).boundingBox();
console.log('games', n, JSON.stringify(box));
rec.mark('tap-mon');
const mon = await games.nth(0).boundingBox();
await page.mouse.click(mon.x + mon.width/2, mon.y + mon.height/2);
await page.waitForTimeout(1700);
await page.screenshot({ path: `${out}/circle-mon.png` });
rec.mark('draw');
await drawCircle(page, box);
await page.waitForTimeout(1600);
await page.screenshot({ path: `${out}/circle-after.png` });
rec.mark('save');
await page.getByRole('button', { name: 'Save', exact: true }).click();
await page.waitForTimeout(2200);
console.log('frames', await rec.stop(`${out}/clip-circle.mp4`));
await page.screenshot({ path: `${out}/circle-saved.png` });
await browser.close();
